/* -----------------------------------------------------------------------
 * Input sampling task (2026-09-18, decoupling from the render/flush loop).
 *
 * board_ui_nav_task's draw+eink_display_fb()/_fast() cycle blocks the
 * whole task for the flush duration (~0.5-1s fast / ~2-4s full). Sampling
 * buttons/touch inline in that same loop (the original design) meant any
 * button or touch edge that started and ended entirely within a flush's
 * blocking window was never read at all — dropped silently, no trace.
 * Physical buttons mostly got away with it (button_wait_press's own
 * blocking-until-release wait means a still-held button is always caught
 * whenever the loop gets back to it), but a quick touch tap frequently
 * didn't survive.
 *
 * Fix: buttons + touch are now sampled continuously in this own task, at
 * their own pace, translated into discrete edge events, and handed to the
 * render task through a queue deep enough to buffer a burst of taps
 * across one flush. The render task drains it with a bounded wait
 * (doubles as its idle-timeout polling tick) instead of sampling hardware
 * directly. REPL/serial input is NOT folded in here — esp_console owns
 * its own task and blocking read loop (main.c) and was never coupled to
 * this one's flush in the first place; it already calls
 * board_activity_notify() directly from its own command handlers.
 * ----------------------------------------------------------------------- */
enum class InputEventType : uint8_t {
    ButtonLeft,
    ButtonRight,
    ButtonPowerActivity,   /* keep-alive only — Power is never acted on here */
    TouchPress,
    TouchRelease,
};

struct InputEvent {
    InputEventType type;
    int16_t x = 0;
    int16_t y = 0;
    bool home = false;
    int16_t raw_x = 0;   /* pre-calibration GT911 values -- carried through
                          * just for the touch diagnostic screen, never
                          * used for hit-testing (see touch.h/.c). */
    int16_t raw_y = 0;
};

static constexpr size_t kInputQueueLen = 16;
static QueueHandle_t s_input_queue = nullptr;
static bool s_touch_ok = false;

static void input_sampler_task(void *arg)
{
    (void)arg;
    /* Decisive diagnostic (2026-09-18): zero dependency on touch/eink --
     * if this doesn't show up either, the problem is upstream of
     * anything touch-specific (task never scheduled, or its serial
     * output specifically never reaching the terminal). Raw printf +
     * fflush alongside ESP_LOGE: disambiguates "task never runs" from
     * "something ESP_LOG-specific (tag level, vprintf hook) swallows it". */
    printf("\r\n### RAW PRINTF: input_sampler_task ENTER (core=%d) ###\r\n", (int)esp_cpu_get_core_id());
    fflush(stdout);
    ESP_LOGE(TAG, "=== input_sampler_task ENTER (core=%d) ===", (int)esp_cpu_get_core_id());

    /* Debug/diagnosis (2026-09-18): the very first reads right after
     * touch_init() (POR dance + possible 185-byte config upload) are
     * suspect until proven otherwise — untested theory is a stale/garbage
     * point or status bit right after init could fire a spurious tap.
     * Give the controller a short settle window before trusting any edge;
     * logged explicitly so this shows up in the serial monitor if it ever
     * fires, rather than silently masking a real bug. */
    const int64_t touch_settle_until_us = esp_timer_get_time() + 300000;   /* 300 ms */

    bool touch_was_pressed = false;
    int16_t touch_down_x = 0, touch_down_y = 0;
    int16_t touch_down_raw_x = 0, touch_down_raw_y = 0;
    bool touch_down_home = false;

    while (1) {
        /* Left/Right only — Power (BTN_3) stays exclusively owned by
         * power_mgr / power_button_task (main.c), never acted on here.
         * button_wait_press blocks until release when a button IS held,
         * which is fine in this dedicated task (it no longer stalls the
         * render/flush loop). */
        button_id_t btn = button_wait_press(20);
        if (btn == BTN_1) {
            /* 2026-09-18: capture-side timestamp, paired with a
             * processing-side one in apply_input_event() -- compares
             * button_wait_press()'s own debounce/release-wait latency
             * against however long the event then sits queued behind a
             * busy render/flush loop, to tell the two apart. */
            ESP_LOGI(TAG, "button LEFT captured");
            InputEvent ev{InputEventType::ButtonLeft};
            xQueueSend(s_input_queue, &ev, 0);
        } else if (btn == BTN_2) {
            ESP_LOGI(TAG, "button RIGHT captured");
            InputEvent ev{InputEventType::ButtonRight};
            xQueueSend(s_input_queue, &ev, 0);
        } else if (btn == BTN_3) {
            ESP_LOGI(TAG, "button POWER captured (activity only)");
            InputEvent ev{InputEventType::ButtonPowerActivity};
            xQueueSend(s_input_queue, &ev, 0);
        }

        if (s_touch_ok) {
            touch_point_t tp = touch_read();
            const bool press_edge = tp.pressed && !touch_was_pressed;
            const bool release_edge = !tp.pressed && touch_was_pressed;

            if (press_edge || release_edge) {
                ESP_LOGI(TAG, "touch %s: x=%d y=%d home=%d raw=(%d,%d)%s",
                         press_edge ? "press" : "release", tp.x, tp.y, (int)tp.home,
                         tp.raw_x, tp.raw_y,
                         esp_timer_get_time() < touch_settle_until_us ? " [settle-ignored]" : "");
            }

            if (esp_timer_get_time() >= touch_settle_until_us) {
                if (press_edge) {
                    touch_down_x = tp.x;
                    touch_down_y = tp.y;
                    touch_down_raw_x = tp.raw_x;
                    touch_down_raw_y = tp.raw_y;
                    touch_down_home = tp.home;
                    InputEvent ev{InputEventType::TouchPress, tp.x, tp.y, tp.home, tp.raw_x, tp.raw_y};
                    xQueueSend(s_input_queue, &ev, 0);
                }
                if (release_edge) {
                    InputEvent ev{InputEventType::TouchRelease, touch_down_x, touch_down_y,
                                  touch_down_home, touch_down_raw_x, touch_down_raw_y};
                    xQueueSend(s_input_queue, &ev, 0);
                }
            }
            touch_was_pressed = tp.pressed;
        }
    }
}

/* TESTING ONLY (2026-09-18) — deep sleep drops the USB-serial-JTAG
 * connection, which was making it impossible to tell whether a touch
 * test actually triggered Sleep or something else: the log line proving
 * it either never got flushed before the disconnect, or the terminal
 * missed it across the reconnect. Set to 0 to restore real sleep once
 * touch behavior is understood — do not ship with this at 1. */
#define MSF_DEBUG_NO_SLEEP 1

static void enter_sleep_from_idle_or_menu(const char *reason)
{
#if MSF_DEBUG_NO_SLEEP
    ESP_LOGW(TAG, "sleep button activated (%s) -- MSF_DEBUG_NO_SLEEP=1, staying awake", reason);
    return;
#else
    if (!power_mgr_claim_terminal_action()) {
        /* Another path (Power long-press, REPL `sleep`) already won the
         * race — nothing to do, it's handling the transition. */
        return;
    }
    ESP_LOGI(TAG, "entering sleep (%s)", reason);
    board_sleep_screen_show();
    power_mgr_shutdown();   /* never returns on success */
#endif
}

/* Primary action slot's Y (2026-09-18): shared between draw_fixed_zone()'s
 * Settings button (Home) and draw_back_and_title()'s "< Back" button
 * (everywhere else) -- same physical position regardless of which one
 * occupies it. */
static constexpr int16_t kHeaderActionY = 76;

/* -----------------------------------------------------------------------
 * Fixed zone (UI-SPECS.md §1.3): battery icon/%, a divider line, and
 * "Settings" -- a button on Home (reachable both by direct tap and by
 * Left/Right), or a plain label once already inside the Settings
 * hierarchy. No date/time yet -- time_svc/RTC isn't wired into the UI
 * layer, that slot stays reserved per §1.3 until it is.
 * ----------------------------------------------------------------------- */
static int16_t draw_fixed_zone(DisplayTarget &target, AppFrame &frame, int16_t screen_width)
{
    /* Battery % + status icon (ADR-014, CW2017 already validated at the
     * driver level). Icon (2026-09-18): Lucide battery-{charging,full,
     * medium,low,warning}, generated by tools/gen_icons.py into
     * battery_icons_gen.h — see docs/esp-project-boilerplate/ for why
     * Lucide (freeink-sdk's icon set) rather than LVGL's default Font
     * Awesome. Charging takes priority over the SoC-based icon; no
     * dedicated "critical" icon in Lucide's set, battery-warning fills
     * that role. Not cached: one I2C read per redraw is cheap enough at
     * this refresh rate (button presses/taps, not a fast loop). */
    uint8_t soc = 0;
    bool charging = false;
    bool have_battery = battery_read(&soc, &charging);

    /* Icon doubled 2026-09-18 (user request: the header has enough
     * thickness to afford it) -- 24px -> 48px. The text next to it
     * (below) stays the default font/size, matching the rest of the
     * screen -- only the icon scales up. */
    const freeink::Icon *battery_icon = &icon_battery_48;
    if (have_battery) {
        if (charging) {
            battery_icon = &icon_battery_charging_48;
        } else if (soc >= 80) {
            battery_icon = &icon_battery_full_48;
        } else if (soc >= 50) {
            battery_icon = &icon_battery_medium_48;
        } else if (soc >= 20) {
            battery_icon = &icon_battery_low_48;
        } else {
            battery_icon = &icon_battery_warning_48;
        }
    }

    const int16_t icon_x = static_cast<int16_t>(screen_width - 48 - 12);
    const int16_t icon_y = 8;
    target.bitmap(Rect{icon_x, icon_y, 48, 48}, bitmapFromIcon(*battery_icon), BitmapMode::Contain);

    char battery_text[8];
    if (have_battery) {
        snprintf(battery_text, sizeof(battery_text), "%u%%", (unsigned)soc);
    } else {
        snprintf(battery_text, sizeof(battery_text), "--");
    }
    TextStyle battery_style;
    /* Default font (slot 0, kNotoSansFont ~24px) -- 2026-09-18, user
     * request: match the rest of the screen's text instead of a
     * dedicated MediumFont sized to the icon. Only the icon stays
     * doubled (24px -> 48px); the text no longer scales with it. */
    battery_style.align = TextAlign::Right;
    /* DisplayTarget::text() places multi-glyph runs at baseline =
     * rect.y + font.ascent, not a vertical center of rect.height. The
     * formula-derived rect.y (icon_y+7, from kNotoSansFont's metrics)
     * still sat a few px low in practice (2026-09-18 hardware check) --
     * nudged up empirically rather than re-deriving the formula, same
     * as every other font-alignment fix in this function. */
    target.text(Rect{static_cast<int16_t>(icon_x - 158), static_cast<int16_t>(icon_y + 2), 150, 48},
                battery_text, battery_style);

    target.line(Point{0, 64}, Point{screen_width, 64}, 1, Paint::solid(Color::Black));

    /* Primary action slot, Rect{24,76,130,36} -- always the same spot,
     * whatever occupies it: a "Settings" button on Home (the only way
     * to enter the Settings hierarchy), or (2026-09-18) the "< Back"
     * button drawn by draw_back_and_title() on every screen under it --
     * back replaces the button that would otherwise sit there, same
     * slot, so the primary action stays in one consistent place across
     * screens instead of jumping around. Nothing drawn here directly
     * for non-Home screens; draw_back_and_title() (called by each
     * sub-screen right after this function returns) fills it.
     *
     * Positioned below the header line (2026-09-18): the earlier fix
     * (Rect{10,10,...} -> Rect{24,20,...}) reduced but never eliminated
     * a direct-tap miss right at the top of the panel -- a hardware
     * test (4-corner+center, docs/touch-calibration-notes.md) showed
     * the touch sensor's active area only starts around raw_y~21 (just
     * below where this row used to sit). Moving the only *interactive*
     * element in the header below the divider line puts it solidly
     * inside the confirmed-active area instead of right at its fragile
     * top edge. */
    if (s_screen == Screen::Home) {
        ButtonProps settings_btn;
        settings_btn.label = "Settings";
        settings_btn.action = ACTION_OPEN_SETTINGS;
        button(frame, Rect{24, kHeaderActionY, 130, 36}, settings_btn);
    } else {
        /* Non-interactive now that it's not a button (2026-09-18, user
         * request) -- moved up into the header proper, alongside the
         * icon/battery row, instead of squatting in the action slot
         * that "< Back" now needs. */
        TextStyle settings_label;
        settings_label.bold = true;
        target.text(Rect{24, 16, 200, 40}, "Settings", settings_label);
    }

    return 124;   /* Y offset where each screen's contextual content starts. */
}

/* Footer — mirror of draw_fixed_zone()'s header: one horizontal line,
 * one line of small text below it, fixed at the bottom of every screen.
 * Firmware version + build date/time, both already embedded by the IDF
 * build (esp_app_desc_t) with zero extra bookkeeping on our side: no
 * PROJECT_VER is set (root CMakeLists.txt), so `version` falls back to
 * `git describe --always --dirty` (e.g. "86200cd-dirty"); `date`/`time`
 * are this binary's compile timestamp, not the device's clock (there is
 * no RTC-backed wall clock wired up yet, ADR-... time_svc). */
static void draw_footer(DisplayTarget &target, const Rect &screen)
{
    const int16_t line_y = static_cast<int16_t>(screen.height - 40);
    target.line(Point{0, line_y}, Point{screen.width, line_y}, 1, Paint::solid(Color::Black));

    const esp_app_desc_t *app_desc = esp_app_get_description();
    char buf[96];
    snprintf(buf, sizeof(buf), "%s  %s %s", app_desc->version, app_desc->date, app_desc->time);

    TextStyle footer_style;
    footer_style.font = kSmallFontSlot;
    footer_style.align = TextAlign::Center;
    target.text(Rect{0, static_cast<int16_t>(line_y + 8), screen.width, 24}, buf, footer_style);
}

static void draw_back_and_title(DisplayTarget &target, AppFrame &frame, const Rect &screen,
                                const char *title)
{
    /* Fixed at the same slot draw_fixed_zone() uses for the Settings
     * button on Home (2026-09-18, user request): "< Back" replaces it,
     * same place, rather than sitting lower at the old per-screen
     * content offset -- one consistent primary-action position across
     * every screen instead of it jumping around depending on which
     * screen you're on. */
    ButtonProps back;
    back.label = "< Back";
    back.action = ACTION_BACK;
    button(frame, Rect{24, kHeaderActionY, 130, 36}, back);

    /* title == nullptr skips the centered title entirely (2026-09-18):
     * the top-level Settings screen used to pass "Settings" here, right
     * below a header that -- once it started showing "Settings" as a
     * label for every screen under it, not just a button on Home -- made
     * the exact same word appear three times on screen at once. Kept
     * for sub-screens (Controls & Calibration, About, Touch diagnostic),
     * whose titles are NOT redundant with the header's generic
     * "Settings" label. */
    if (title != nullptr) {
        TextStyle title_style;
        title_style.align = TextAlign::Center;
        title_style.bold = true;
        target.text(Rect{0, kHeaderActionY, screen.width, 36}, title, title_style);
    }
}

