static const char *screen_name(Screen s)
{
    switch (s) {
    case Screen::Home:             return "Home";
    case Screen::Settings:         return "Settings";
    case Screen::SettingsControls: return "SettingsControls";
    case Screen::SettingsAbout:    return "SettingsAbout";
    case Screen::TouchDiag:        return "TouchDiag";
    }
    return "?";
}

/* UI-SPECS.md §1.1: "Full refresh only on: screen type change ... Everything
 * else uses fast DU refresh." Starts true so the very first draw of the
 * whole task is full too (no previous frame to diff against anyway — the
 * driver would force one either way, but this makes the app's own intent
 * explicit rather than leaning on that fallback). */
static bool s_force_full_refresh = true;

static void switch_screen(Screen s)
{
    ESP_LOGI(TAG, "screen: %s -> %s", screen_name(s_screen), screen_name(s));
    s_screen = s;
    s_force_full_refresh = true;
    /* Focus from the previous screen's widgets doesn't correspond to
     * anything on the new one — start with nothing focused rather than a
     * stale/out-of-range index. */
    s_interactions.setFocusedIndex(-1);
}

/* ADR-012: idle timeout (no button/touch/serial input) before auto-sleep.
 * Runtime value, not a compile-time constant — settings_store.h's
 * settings_store_get_idle_timeout_s() (0 = disabled, dev default per its
 * own doc comment; a shipped device should default to 45s). */
static std::atomic<int64_t> s_last_activity_us{0};

void board_activity_notify(void)
{
    s_last_activity_us.store(esp_timer_get_time(), std::memory_order_relaxed);
}

/* UI-SPECS.md §2.12/§3: a short Power press-and-release (main.c's
 * power_button_task, gated behind the "Power short press = Select"
 * setting) injects one confirm pulse here, equivalent to a touch-Home
 * tap. Power never joins this loop's own input reads — this is a single
 * pending flag consumed by the next iteration. */
static std::atomic<bool> s_power_confirm_pending{false};

void board_ui_nav_power_confirm(void)
{
    s_power_confirm_pending.store(true, std::memory_order_relaxed);
}

