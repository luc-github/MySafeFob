/* -----------------------------------------------------------------------
 * Touch diagnostic (simplified from UI-SPECS.md §2.12's full 3x3 guided
 * grid — this pass ships the "minimum useful" version the spec itself
 * calls out: a live raw-coordinate readout, updated from the same touch
 * sample the main loop already reads every cycle. No fix/reprogram
 * attempt here (docs/touch-calibration-notes.md) — diagnosis only.
 * ----------------------------------------------------------------------- */
static touch_point_t s_last_touch = { false, false, -1, -1, 0, 0 };

/* Small "+" marker so a calibration tap has an unambiguous, precise
 * target instead of "somewhere near this corner" -- the ambiguity that
 * slowed down every earlier round of this calibration effort (verbally
 * matching a tap to a log line after the fact). */
static void draw_crosshair(DisplayTarget &target, int16_t x, int16_t y)
{
    constexpr int16_t kArm = 10;
    target.line(Point{static_cast<int16_t>(x - kArm), y}, Point{static_cast<int16_t>(x + kArm), y},
                1, Paint::solid(Color::Black));
    target.line(Point{x, static_cast<int16_t>(y - kArm)}, Point{x, static_cast<int16_t>(y + kArm)},
                1, Paint::solid(Color::Black));
}

static void draw_touch_diag(DisplayTarget &target, AppFrame &frame, const Rect &screen, int16_t y)
{
    draw_back_and_title(target, frame, screen, "Touch diagnostic");

    TextStyle body;
    body.align = TextAlign::Center;
    char buf1[48];
    char buf2[48];
    if (s_last_touch.x >= 0) {
        /* Both stages shown (2026-09-18, calibration is still unresolved,
         * docs/touch-calibration-notes.md): "logical" is what actually
         * gets hit-tested against widget Rects ((EINK_H-1)-raw_x on X,
         * touch_rescale_y() on Y); "raw" is the untouched GT911 register
         * value. Showing both side by side removes the "which stage did
         * this logged number come from" ambiguity that slowed down the
         * last few calibration rounds. */
        snprintf(buf1, sizeof(buf1), "logical: x=%d y=%d%s", s_last_touch.x, s_last_touch.y,
                 s_last_touch.home ? "  (home)" : "");
        snprintf(buf2, sizeof(buf2), "raw: x=%d y=%d", s_last_touch.raw_x, s_last_touch.raw_y);
    } else {
        snprintf(buf1, sizeof(buf1), "tap the screen");
        buf2[0] = '\0';
    }
    target.text(Rect{0, static_cast<int16_t>(y + 20), screen.width, 32}, buf1, body);
    target.text(Rect{0, static_cast<int16_t>(y + 56), screen.width, 32}, buf2, body);

    /* Five explicit targets (2026-09-18): tap each one at a time, exactly
     * on the crosshair's center, and read the two lines above after each
     * tap -- removes the need to describe "roughly which corner" in
     * words. Placed well clear of the header (button at y=76-112) and
     * footer (line at screen.height-40) so they don't visually clash with
     * either. */
    const int16_t left = 20;
    const int16_t right = static_cast<int16_t>(screen.width - 20);
    const int16_t cx = static_cast<int16_t>(screen.width / 2);
    const int16_t top = 240;
    const int16_t mid = 440;
    const int16_t bottom = 640;
    draw_crosshair(target, left, top);
    draw_crosshair(target, right, top);
    draw_crosshair(target, cx, mid);
    draw_crosshair(target, left, bottom);
    draw_crosshair(target, right, bottom);
}

/* -----------------------------------------------------------------------
 * Dispatch
 * ----------------------------------------------------------------------- */
static void draw_current_screen(DisplayTarget &target, AppFrame &frame)
{
    memset(s_fb, 0xFF, sizeof(s_fb));
    const Rect screen = frame.screen();
    int16_t content_y = draw_fixed_zone(target, frame, screen.width);

    switch (s_screen) {
    case Screen::Home:             draw_home(target, frame, screen, content_y); break;
    case Screen::Settings:         draw_settings(target, frame, screen, content_y); break;
    case Screen::SettingsControls: draw_settings_controls(target, frame, screen, content_y); break;
    case Screen::SettingsAbout:    draw_settings_about(target, frame, screen, content_y); break;
    case Screen::TouchDiag:        draw_touch_diag(target, frame, screen, content_y); break;
    }

    draw_footer(target, screen);
}

static void handle_action(ActionId action)
{
    ESP_LOGI(TAG, "action: %d (screen=%s)", (int)action, screen_name(s_screen));
    switch (action) {
    case ACTION_SLEEP_NOW:
        enter_sleep_from_idle_or_menu("Sleep now menu item");
        break;
    case ACTION_OPEN_SETTINGS:
        if (s_screen == Screen::Home) {
            s_settings_return_to = Screen::Home;
        }
        switch_screen(Screen::Settings);
        break;
    case ACTION_BACK:
        switch (s_screen) {
        case Screen::Settings:         switch_screen(s_settings_return_to); break;
        case Screen::SettingsControls: switch_screen(Screen::Settings); break;
        case Screen::SettingsAbout:    switch_screen(Screen::Settings); break;
        case Screen::TouchDiag:        switch_screen(Screen::SettingsControls); break;
        default: break;
        }
        break;
    case ACTION_OPEN_CONTROLS:
        switch_screen(Screen::SettingsControls);
        break;
    case ACTION_OPEN_ABOUT:
        switch_screen(Screen::SettingsAbout);
        break;
    case ACTION_OPEN_TOUCH_DIAG:
        switch_screen(Screen::TouchDiag);
        break;
    case ACTION_TOGGLE_POWER_CONFIRM:
        settings_store_set_power_short_confirm(!settings_store_get_power_short_confirm());
        break;
    default:
        break;
    }
}

/* Translates one queued InputEvent into the InputSnapshot fields
 * Frame/InteractionBuffer expect. Factored out so the coalescing loop in
 * board_ui_nav_task can apply it to more than just the first event of a
 * burst. */
static void apply_input_event(const InputEvent &inev, InputSnapshot &input)
{
    switch (inev.type) {
    case InputEventType::ButtonLeft:
        ESP_LOGI(TAG, "button LEFT processed (dequeued)");
        input.focusPrev = true;
        break;
    case InputEventType::ButtonRight:
        ESP_LOGI(TAG, "button RIGHT processed (dequeued)");
        input.focusNext = true;
        break;
    case InputEventType::ButtonPowerActivity:
        break;   /* keep-alive only */
    case InputEventType::TouchPress:
        s_last_touch = {true, inev.home, inev.x, inev.y, inev.raw_x, inev.raw_y};
        input.touchPressed = true;
        input.touchX = inev.x;
        input.touchY = inev.y;
        if (inev.home) input.confirm = true;
        break;
    case InputEventType::TouchRelease:
        input.touchReleased = true;
        input.touchX = inev.x;
        input.touchY = inev.y;
        break;
    }
}

void board_ui_nav_task(void *arg)
{
    (void)arg;

    /* Decisive diagnostic (2026-09-18): see input_sampler_task's twin
     * comment -- logged before touching buttons/touch/eink at all. */
    printf("\r\n### RAW PRINTF: board_ui_nav_task ENTER (core=%d) ###\r\n", (int)esp_cpu_get_core_id());
    fflush(stdout);
    ESP_LOGE(TAG, "=== board_ui_nav_task ENTER (core=%d) ===", (int)esp_cpu_get_core_id());

    buttons_init();
    s_touch_ok = touch_init();
    ESP_LOGI(TAG, "touch: %s", s_touch_ok ? "OK" : "ABSENT");

    s_input_queue = xQueueCreate(kInputQueueLen, sizeof(InputEvent));
    xTaskCreate(input_sampler_task, "ui_input", 4096, NULL, 4, NULL);

    s_last_activity_us.store(esp_timer_get_time(), std::memory_order_relaxed);

    DisplayTarget target(s_fb, EINK_W, EINK_H, EINK_WB, Orientation::Portrait);
    target.setFont(kSmallFontSlot, kNotoSansSmallFont);
    const DeviceContext device = target.deviceContext();

    while (1) {
        InputSnapshot input{};
        bool activity = false;

        /* Bounded wait (also this loop's idle-timeout polling tick) —
         * hardware sampling itself happens in input_sampler_task, never
         * blocked by this task's own eink flush below. */
        InputEvent inev{};
        if (xQueueReceive(s_input_queue, &inev, pdMS_TO_TICKS(50)) == pdTRUE) {
            activity = true;
            apply_input_event(inev, input);

            /* Coalesce a burst of already-queued events (2026-09-18): drain
             * and resolve (but never flush) every event but the last, so N
             * queued button/touch events collapse into a single redraw +
             * flush instead of N sequential ones -- the e-ink flush is the
             * real bottleneck (0.5-4s), not input handling, so 3 quick
             * Right presses no longer mean 3 back-to-back panel updates.
             * Each throwaway resolve still runs draw_current_screen() and
             * handle_action() for real (advancing focus/screen state
             * correctly, mid-burst screen switches included) -- it just
             * never reaches eink_display_fb*(). Capped so a runaway queue
             * can't stall this loop indefinitely. */
            constexpr int kMaxCoalesce = 8;
            for (int i = 0; i < kMaxCoalesce; ++i) {
                InputEvent next{};
                if (xQueueReceive(s_input_queue, &next, 0) != pdTRUE) break;

                AppFrame throwaway(target, device, input, s_interactions);
                draw_current_screen(target, throwaway);
                ActionEvent throwaway_ev = throwaway.finish();
                if (throwaway_ev) handle_action(throwaway_ev.action);

                input = InputSnapshot{};
                apply_input_event(next, input);
            }
        }

        if (s_power_confirm_pending.exchange(false, std::memory_order_relaxed)) {
            activity = true;
            input.confirm = true;
        }

        if (activity) {
            board_activity_notify();
        }

        const bool changed = s_force_full_refresh || input.focusPrev || input.focusNext ||
                             input.confirm || input.touchPressed || input.touchReleased;
        if (!changed) {
            uint32_t idle_timeout_s = settings_store_get_idle_timeout_s();
            if (idle_timeout_s > 0) {
                int64_t idle_ms = (esp_timer_get_time() - s_last_activity_us.load(std::memory_order_relaxed)) / 1000;
                if (idle_ms >= (int64_t)idle_timeout_s * 1000) {
                    enter_sleep_from_idle_or_menu("idle timeout, no button/touch/serial input");
                    /* Only reaches here if another caller already claimed the
                     * transition — avoid re-triggering every 50ms while that
                     * transition is in flight. */
                    vTaskDelay(pdMS_TO_TICKS(1000));
                }
            }
            continue;
        }

        /* Pass 1 (thrown away on screen, just to register hit-rects):
         * resolves the current input -> updates focused_/active_. */
        AppFrame frame(target, device, input, s_interactions);
        draw_current_screen(target, frame);
        ActionEvent ev = frame.finish();

        if (ev) {
            handle_action(ev.action);
        }

        /* Pass 2: real draw with the now-current focus/active state (and
         * whatever screen handle_action() may have just switched to) — the
         * one that actually gets flushed, eliminating the one-frame lag. */
        AppFrame frame2(target, device, InputSnapshot{}, s_interactions);
        draw_current_screen(target, frame2);

        if (s_force_full_refresh) {
            eink_display_fb(s_fb);
            s_force_full_refresh = false;
        } else {
            eink_display_fb_fast(s_fb);
        }
    }
}
