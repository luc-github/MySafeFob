#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_logo.py — converts resources/logo-only.png into an LVGL 9 image for
the app (boards/x4pro/app/images/msf_logo.c).

The PNG is flattened on white, cropped to its ink, resized to HEIGHT pixels
(aspect kept, Lanczos), then thresholded: the panel is 1-bit, so a clean
black/white mask beats letting the renderer threshold anti-aliased edges.
Output format is LV_COLOR_FORMAT_A8 (0 or 255 per pixel): LVGL draws an A8
image in the object's image_recolor color, black by default.

Same approach as gen_fonts.py: the generated file is committed, this script
is only run when the logo changes (then rebuild).
Needs Pillow.  Usage:  python tools/gen_logo.py
"""
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "resources", "logo-only.png")
OUT = os.path.join(ROOT, "boards", "x4pro", "app", "images", "msf_logo.c")
NAME = "msf_logo"
HEIGHT = 52          # fits HOME's header strip (kHeaderInfoHeight - kHeaderContentPadTop = 57)
THRESHOLD = 128      # ink when the resized luminance is darker than this

HEADER = """/*
 Project: MySafeFob  msf_logo.c
  Copyright (c) 2026 Luc Lebosse. All rights reserved.

  This code is free software; you can redistribute it and/or
  modify it under the terms of the GNU Lesser General Public
  License as published by the Free Software Foundation; either
  version 2.1 of the License, or (at your option) any later version.

  This code is distributed in the hope that it will be useful,
  but WITHOUT ANY WARRANTY; without even the implied warranty of
  MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the GNU
  Lesser General Public License for more details.

  You should have received a copy of the GNU Lesser General Public
  License along with this library; if not, write to the Free Software
  Foundation, Inc., 51 Franklin St, Fifth Floor, Boston, MA  02110-1301  USA
*/
"""


def main():
    src = Image.open(SRC).convert("RGBA")
    bg = Image.new("RGBA", src.size, (255, 255, 255, 255))
    gray = Image.alpha_composite(bg, src).convert("L")
    ink = gray.point(lambda v: 255 - v)                 # ink = 255
    bbox = ink.point(lambda v: 255 if v >= THRESHOLD else 0).getbbox()
    ink = ink.crop(bbox)
    width = max(1, round(ink.width * HEIGHT / ink.height))
    ink = ink.resize((width, HEIGHT), Image.LANCZOS)
    alpha = bytes(255 if v >= THRESHOLD else 0 for v in ink.tobytes())

    lines = [HEADER,
             f"/* GENERATED by tools/gen_logo.py from resources/logo-only.png, do not edit.\n"
             f" * {width}x{HEIGHT}, LV_COLOR_FORMAT_A8 (0 = transparent, 255 = ink). */\n",
             '#include "lvgl.h"\n\n',
             f"static const uint8_t {NAME}_data[] = {{\n"]
    for y in range(HEIGHT):
        row = alpha[y * width:(y + 1) * width]
        lines.append("    " + ",".join(f"0x{b:02X}" for b in row) + ",\n")
    lines.append("};\n\n")
    lines.append(f"const lv_image_dsc_t {NAME} = {{\n"
                 f"    .header = {{\n"
                 f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
                 f"        .cf = LV_COLOR_FORMAT_A8,\n"
                 f"        .flags = 0,\n"
                 f"        .w = {width},\n"
                 f"        .h = {HEIGHT},\n"
                 f"        .stride = {width},\n"
                 f"    }},\n"
                 f"    .data_size = sizeof({NAME}_data),\n"
                 f"    .data = {NAME}_data,\n"
                 f"}};\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(lines))
    print(f"-> {os.path.relpath(OUT, ROOT)} ({width}x{HEIGHT})")
    # ASCII preview, to check the details survived the downscale.
    for y in range(HEIGHT):
        print("".join("#" if alpha[y * width + x] else "." for x in range(width)))


if __name__ == "__main__":
    main()
